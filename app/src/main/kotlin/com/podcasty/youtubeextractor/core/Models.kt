package com.podcasty.youtubeextractor.core

data class Subtitle(
    val start: String,
    val dur: String,
    val text: String,
) {
    val startSeconds: Double get() = start.toDoubleOrNull() ?: 0.0
    val durationSeconds: Double get() = dur.toDoubleOrNull() ?: 0.0
    val endSeconds: Double get() = startSeconds + durationSeconds
}

data class VideoDetails(
    val videoId: String,
    val title: String,
    val description: String,
    val subtitles: List<Subtitle>,
    val requestedLanguage: String,
    val selectedLanguage: String? = null,
    val isAutoGenerated: Boolean = false,
    val warning: String? = null,
)

class CaptionExtractionException(
    message: String,
    cause: Throwable? = null,
) : Exception(message, cause)
