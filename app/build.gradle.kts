import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.io.FileInputStream
import java.util.Properties

val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) FileInputStream(f).use { load(it) }
}

fun signingProp(name: String): String? =
    System.getenv(name)?.takeIf { it.isNotBlank() }
        ?: localProps.getProperty(name)?.takeIf { it.isNotBlank() }

val releaseStoreFilePath = signingProp("PODCASTY_RELEASE_STORE_FILE")
val releaseStorePassword = signingProp("PODCASTY_RELEASE_STORE_PASSWORD")
val releaseKeyAlias = signingProp("PODCASTY_RELEASE_KEY_ALIAS")
val releaseKeyPassword = signingProp("PODCASTY_RELEASE_KEY_PASSWORD")
val hasReleaseSigning = !releaseStoreFilePath.isNullOrBlank() &&
    !releaseStorePassword.isNullOrBlank() &&
    !releaseKeyAlias.isNullOrBlank() &&
    !releaseKeyPassword.isNullOrBlank() &&
    file(releaseStoreFilePath).exists()

